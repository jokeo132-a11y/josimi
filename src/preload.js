const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('josimi', {
  config: () => ipcRenderer.invoke('app-config'),
  chooseWalletFile: (action) => ipcRenderer.invoke('wallet-file-choose', { action }),
  create: (payload) => ipcRenderer.invoke('wallet-create', payload),
  restore: (payload) => ipcRenderer.invoke('wallet-restore', payload),
  open: (payload) => ipcRenderer.invoke('wallet-open', payload),
  refresh: () => ipcRenderer.invoke('wallet-refresh'),
  getSeed: (payload) => ipcRenderer.invoke('wallet-seed', payload),
  createAccount: (payload) => ipcRenderer.invoke('wallet-account-create', payload),
  setAccountLabel: (payload) => ipcRenderer.invoke('wallet-account-label', payload),
  createSubaddress: (payload) => ipcRenderer.invoke('wallet-subaddress-create', payload),
  setSubaddressLabel: (payload) => ipcRenderer.invoke('wallet-subaddress-label', payload),
  addAddressBookEntry: (payload) => ipcRenderer.invoke('wallet-addressbook-add', payload),
  editAddressBookEntry: (payload) => ipcRenderer.invoke('wallet-addressbook-edit', payload),
  deleteAddressBookEntry: (payload) => ipcRenderer.invoke('wallet-addressbook-delete', payload),
  setTransactionNote: (payload) => ipcRenderer.invoke('wallet-transaction-note', payload),
  nodeStatus: () => ipcRenderer.invoke('node-status'),
  localNodeStatus: () => ipcRenderer.invoke('local-node-status'),
  localNodeInstall: () => ipcRenderer.invoke('local-node-install'),
  localNodeStart: () => ipcRenderer.invoke('local-node-start'),
  localNodeStop: () => ipcRenderer.invoke('local-node-stop'),
  miningStatus: () => ipcRenderer.invoke('mining-status'),
  miningStart: (payload) => ipcRenderer.invoke('mining-start', payload),
  miningStop: () => ipcRenderer.invoke('mining-stop'),
  onNodeStatus: (callback) => ipcRenderer.on('node-status', (_, status) => callback(status)),
  onLocalNodeStatus: (callback) => ipcRenderer.on('local-node-status', (_, status) => callback(status)),
  onMiningStatus: (callback) => ipcRenderer.on('mining-status', (_, status) => callback(status)),
  lock: () => ipcRenderer.invoke('wallet-lock'),
  previewSend: (payload) => ipcRenderer.invoke('wallet-send-preview', payload),
  cancelSend: (payload) => ipcRenderer.invoke('wallet-send-cancel', payload),
  pendingSend: () => ipcRenderer.invoke('wallet-send-pending'),
  resolvePendingSendRecovery: (payload) => ipcRenderer.invoke('wallet-send-resolve-recovery', payload),
  ackSend: (payload) => ipcRenderer.invoke('wallet-send-ack', payload),
  send: (payload) => ipcRenderer.invoke('wallet-send', payload),
  exportBackup: () => ipcRenderer.invoke('wallet-export-backup'),
  qr: (text) => ipcRenderer.invoke('wallet-qr', text)
});
